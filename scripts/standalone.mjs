import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = (name) => readFile(new URL(name, root), 'utf8');

function replaceOnce(html, pattern, replacement) {
  const matches = [...html.matchAll(new RegExp(pattern, pattern.flags + 'g'))];
  if (matches.length !== 1) {
    throw new Error(`Expected one ${pattern} in index.html; found ${matches.length}.`);
  }
  // A function replacement keeps dollar signs in embedded source files literal.
  return html.replace(pattern, () => replacement);
}

const [index, css, engine, app, license] = await Promise.all(
  ['index.html', 'style.css', 'engine.js', 'app.js', 'LICENSE'].map(read),
);

let html = replaceOnce(
  index,
  /<!doctype html>/i,
  '<!doctype html>\n<!-- Generated by npm run build:standalone. Edit the source files and regenerate. -->\n' +
    `<!--\n${license.trimEnd()}\n-->`,
);
html = replaceOnce(html, /<link\b[^>]*href="style\.css"[^>]*>/, `<style>\n${css}</style>`);
for (const name of ['engine', 'app']) {
  html = replaceOnce(
    html,
    new RegExp(`[ \\t]*<script\\b[^>]*src="${name}\\.js"[^>]*>\\s*</script>\\r?\\n?`),
    '',
  );
}
// Inline scripts must run after #app exists; the modular entry point uses defer.
html = replaceOnce(
  html,
  /<\/body>/,
  `<script>\n${engine}</script>\n<script>\n${app}</script>\n  </body>`,
);

if (process.argv.includes('--check')) {
  let current;
  try {
    current = await read('Rank-Anything.html');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current !== html) {
    console.error('Rank-Anything.html is missing or stale. Run npm run build:standalone.');
    process.exitCode = 1;
  } else {
    console.log('Standalone HTML matches the source files and license.');
  }
} else {
  await writeFile(new URL('Rank-Anything.html', root), html);
  console.log('Generated Rank-Anything.html.');
}
